"""
Build the source pools for tagging and fusion. Each row: {"id", "text", "domain", "meta"}.

math:    stratified slice of GAR's NuminaMath base set (every Problem_type kept, large types capped).
puzzles: logic puzzles generated by reasoning-gym (Apache-2.0); the reference answer is kept in meta for
         formalization-faithfulness checks only. The solver is still verified by Lean.
"""
import argparse
import json
import os
import random
import sys
import types
from collections import defaultdict

PUZZLE_FAMILIES = ["knights_knaves", "mini_sudoku", "futoshiki", "graph_color", "kakurasu", "self_reference",
                   "syllogism", "n_queens"]


def write(rows, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
    print(f"wrote {len(rows)} rows to {path}")


def math_pool(base, cap, seed):
    by_type = defaultdict(list)
    with open(base, encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            by_type[str(r.get("Problem_type"))].append(r)
    rng = random.Random(seed)
    rows = []
    for t in sorted(by_type):
        items = by_type[t] if len(by_type[t]) <= cap else rng.sample(by_type[t], cap)
        rows += [{"id": r["Name"], "text": r["Natural_language_statement"], "domain": "math",
                  "meta": {"Problem_type": t, "idx": r["idx"]}} for r in items]
    return rows


def puzzle_pool(per_family, seed):
    # zebra_puzzles needs pycosat, which has no wheel for this Python; the stub only lets the package import
    stub = types.ModuleType("pycosat")
    stub.solve = stub.itersolve = lambda *a, **k: (_ for _ in ()).throw(RuntimeError("pycosat unavailable"))
    sys.modules.setdefault("pycosat", stub)
    import reasoning_gym as rg
    rows = []
    for fam in PUZZLE_FAMILIES:
        ds = rg.create_dataset(fam, size=per_family, seed=seed)
        for i in range(per_family):
            x = ds[i]
            rows.append({"id": f"{fam}_{i:04d}", "text": x["question"], "domain": "puzzles",
                         "meta": {"family": fam, "answer": None if x["answer"] is None else str(x["answer"])}})
    return rows


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("domain", choices=["math", "puzzles"])
    ap.add_argument("--base", default="base_data/GAR_base_data_Numina-Math.json")
    ap.add_argument("--cap", type=int, default=4000, help="math: max problems per Problem_type")
    ap.add_argument("--per_family", type=int, default=400, help="puzzles: puzzles per family")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    rows = math_pool(a.base, a.cap, a.seed) if a.domain == "math" else puzzle_pool(a.per_family, a.seed)
    write(rows, a.out or f"tagging/{a.domain}/pool.jsonl")
