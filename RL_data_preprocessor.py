class RL_DataPreprocessor:
    def __init__(self, 
                 tokenizer, 
                 generated_dataset_path: str, 
                 recorded_input: bool = True):
        """
        Initializes the RL_DataPreprocessor with a tokenizer and a generated dataset path.
        :param tokenizer: The tokenizer to be used for formatting the prompts.
        :param generated_dataset_path: The path to the generated dataset where the LLM roll-out data were saved. Inside the dir, the document structure should be:
            - save_file_step-i_j: The generated dataset for the i-th step of RL training, where j is the index for data roll-out when saperated to multiple GPU.
                - verified_proofs.json: The json file containing the proofs after verification. It should be a list of dict, where each inner dict should contain at least:
                    - "Name": The name of generated theorem, which is used to identify the theorem.
                    - "Statement": The statement of the theorem.
                    - "Generation_log": The log for generation:
                        - "Statement_fusion_log": The log for statement fusion, which is a dict contain the following:
                            - "Base_statements": The base statements for statement fusion, which is a list of strings.
                            - "Input": The input for the statement fusion, which is the **formatted** prompt.
                            - "Response": The response for the statement fusion, which is the **formatted** prompt as well as the LLM response.
                    - "Proof_generation_log": The log for proof generation, which is a list of dict, where each inner dict should contain at least:
                        - "generation_idx": The index of the generation, which is used to identify the generation.
                        - "generated_content": The generated content, which is the **formatted** prompt as well as the LLM response.
                        - "Input": The input for the statement fusion, which is the **formatted** prompt.
                    - "Proof_verification_log": The log for proof verification, which is a list of dict where each inner dict should contain at least:
                        - "custom_id": The custom id for the verification, which is used for the Lean-server to identify. Note since there maybe identical proof generated by LLM, this id is the same as the "generation_idx" in the proof generation log.
                        - "proof": The proof content, which is the pure Lean4 code without any other natural language content expect for comments.
                        - "pass": A boolean value indicating whether the proof passes the verification.
                    - "pass_rate": The pass rate of the proof verification, which is a float value between 0 and 1.

        :param recorded_input: If True, it means the dataset has recorded the input to the LLM, we do not need to perform extraction of the input text from the response.
            If False, it means the dataset has not recorded the input to the LLM, we need to extract the input text from the response using the `_Qwen3_extract_prompt_and_response` or other similar functions.
        """
        self.tokenizer = tokenizer
        self.base_dataset_path = generated_dataset_path
        self.verified_proofs = []
        self.recorded_input = recorded_input

        for subfolder_name in os.listdir(self.base_dataset_path):
            subfolder_path = os.path.join(self.base_dataset_path, subfolder_name)
            print(f"Loading verified proofs from {subfolder_path}...")
            if os.path.isdir(subfolder_path):
                result_file_path = os.path.join(subfolder_path, "verified_proofs.json")
                if os.path.isfile(result_file_path):
                    curr_verified_proofs = utils.read_from_json(result_file_path)
                else:
                    continue
            self.verified_proofs.extend(curr_verified_proofs)

        # calculate the statement modification rate for each record
        for curr_thm_record in self.verified_proofs:
            curr_thm_statement = curr_thm_record["Statement"]
            if "Proof_verification_log" in curr_thm_record and "Proof_generation_log" in curr_thm_record:
                generation_log_dict = {log["generation_idx"]: log for log in curr_thm_record["Proof_generation_log"]}

                total_verifications = len(curr_thm_record["Proof_verification_log"])
                if total_verifications == 0:
                    curr_thm_record["statement_modification_rate"] = 0.0
                    continue

                modified_count = 0
                valid_proof_count = 0
                for curr_verification_log in curr_thm_record["Proof_verification_log"]:
                    if "custom_id" in curr_verification_log and curr_verification_log["custom_id"] in generation_log_dict:
                        curr_verified_proof = curr_verification_log["proof"]
                        if utils.judge_statement_modification(curr_thm_statement, curr_verified_proof):
                            modified_count += 1
                            curr_verification_log["statement_modified"] = True
                        else:
                            curr_verification_log["statement_modified"] = False
                        valid_proof_count += 1
                if valid_proof_count != 0:
                    curr_thm_record["statement_modification_rate"] = modified_count / valid_proof_count
                else:
                    curr_thm_record["statement_modification_rate"] = 0.0

        if len(self.verified_proofs) == 0:
            raise RuntimeError("All GAR forward worker failed, raise error")

    def _split_chat_prompt(self, 
                           text_to_split: str, 
                           split_token: str = "<|im_start|>assistant"):
        """
        This helper function splits the text into two parts based on the split token, if there are multiple split tokens, it will only split at the first one.
        :param text_to_split: The text to be split.
        :param split_token: The token to split the text, default is "<|im_start|>assistant".

        :return: A tuple of splitted text, we will ignore the final \\n in the first part. Additionally, if the split token is not found in the text, it will return None.
        """
        if split_token in text_to_split:
            idx = text_to_split.index(split_token)
            input_part = text_to_split[:idx].strip()
            output_part = text_to_split[idx + len(split_token):].strip()
            return [input_part, output_part]
        else:
            return None

    def _Qwen3_extract_prompt_and_response(
            self, 
            text_to_extract: str, 
            skip_thinking: bool = True
    ) -> Dict[str, str]:
        """
        This is the helper function that extracts the input and output text from the combined string of Qwen3 input and output formatted string.
        By default, the generation prompt will be in the input text.
        :param text_to_extract: The combined string of Qwen3 input and output formatted string.
        :param skip_thinking: If True, it will put the <think>\n\n</think> part in the input text, else, it will keep it in the output text
        
        :return: A dict containing the following keys:
            - "input": The input text for the model, which is the prompt and , in the Qwen3 case, it will also include the <think>\n\n<\\think> part if skip_thinking is False.
            - "output": The output text for the model, which is the generated content.
        """

        splitted_content = self._split_chat_prompt(text_to_extract, split_token="<|im_start|>assistant")
        if splitted_content is None:
            return None
        
        if skip_thinking:
            input_text = splitted_content[0] + "\n<|im_start|>assistant\n<think>\n\n</think>\n"
        else:
            input_text = splitted_content[0] + "\n<|im_start|>assistant\n"
        output_text = splitted_content[1]

        if output_text.startswith("<think>\n\n</think>") and skip_thinking:
            output_text = output_text[len("<think>\n\n</think>"):].strip()

        if not (output_text.endswith(self.tokenizer.eos_token) or output_text.endswith(self.tokenizer.pad_token)):
            output_text += self.tokenizer.eos_token
        return {
            "input": input_text,
            "output": output_text
        }
    
    def preprocess_Prover_training_data(
            self, 
            processed_data_save_path: str,
            max_pass_rate: float = 0.5, 
            min_pass_rate: float = 0.0,
            LLM_type: str = "Qwen3"
    ):
        """
        This function preprocesses the data for the Prover RL training, it will filter the data based on the pass rate to ensure that 
        the training data has suitable degree of difficulty.
        It will process the class-saved dataset into a list of dict following the following format:
            - "name": The name of the theorem, which is used to uniquely identify the theorem.
            - "training_data": The training data for the model, which is obtained by generating the formal proof using the LLM for multiple times. It should be a list of dict, where the inner dict contains the following keys:
                - "generation_idx": The index of the generation, which is used to identify the generation.
                - "input": The input text for the model, which is the prompt together with any necessary formatting string like the generation header.
                - "output": The output text of the model, which is the generated content. 
                - "correctness": A bool variable indicating whether the generated content passes the verification.
                - "statement_modified": A bool variable indicating whether the statement is modified during the proof generation, this is useful in punishing the model for modifying the statement
        :param processed_data_save_path: The path to save the processed data. It will save the entire processed data as a json file named `processed_prover_training_data.json` representing list of dict.
        :param max_pass_rate: The max pass rate for the data to be included in the training data, default is 0.5. This is to ensure that the training data is not too easy to solve.
        :param min_pass_rate: The min pass rate for the data to be included in the training data, default is 0.0. This is to ensure that the training data is not impossible to solve.
        :param LLM_type: The type of the LLM, default is "Qwen3". It will be used to extract the input and the output text from the generated content.
        """

        utils.check_folder_exit(processed_data_save_path)
        
        processed_data = []
        
        for curr_data_record in tqdm(self.verified_proofs):
            if "pass_rate" not in curr_data_record:
                print(f"Skipping record {curr_data_record['Name']} due to missing pass rate.")
                continue
            elif not (min_pass_rate < curr_data_record["pass_rate"] <= max_pass_rate):
                # print(f"Skipping record {curr_data_record['Name']} due to pass rate {curr_data_record['pass_rate']} not in range [{min_pass_rate}, {max_pass_rate}].")
                continue
            if "Proof_generation_log" not in curr_data_record or len(curr_data_record["Proof_generation_log"]) == 0:
                print(f"Skipping record {curr_data_record['Name']} due to missing proof generation log.")
                continue
            if "Proof_verification_log" not in curr_data_record or len(curr_data_record["Proof_verification_log"]) == 0:
                print(f"Skipping record {curr_data_record['Name']} due to missing proof verification log.")
                continue
            
            curr_training_data = []

            generation_log_dict = {curr_log["generation_idx"]: curr_log for curr_log in curr_data_record["Proof_generation_log"]}

            for curr_verification_log in curr_data_record["Proof_verification_log"]:
                if "custom_id" not in curr_verification_log:
                    print(f"Skipping one record for {curr_data_record['Name']} due to missing custom id in the proof verification log.")
                    continue
                if curr_verification_log["custom_id"] not in generation_log_dict:
                    if not "wrong_proof" in curr_verification_log["custom_id"]:
                        print(f"Skipping varification id {curr_verification_log['custom_id']} due to missing generation log.")
                    continue
                
                
                curr_pass = curr_verification_log["pass"]
                curr_generation_log = generation_log_dict[curr_verification_log["custom_id"]]

                if self.recorded_input:
                    if "input" in curr_generation_log and "generated_content" in curr_generation_log:
                        curr_input = curr_generation_log["input"]
                        curr_output = curr_generation_log["generated_content"][len(curr_input):]
                else:
                    if "generated_content" not in curr_generation_log:
                        print(f"Skipping varification id {curr_verification_log['custom_id']} due to missing generated content in the generation log.")
                        continue
                    extracted_data = self._Qwen3_extract_prompt_and_response(
                        curr_generation_log["generated_content"], 
                        skip_thinking=False
                    )
                    if extracted_data is None:
                        print(f"Varification id {curr_verification_log['custom_id']} due to failed extraction of prompt and response.")
                        continue
                    curr_input = extracted_data["input"]
                    curr_output = extracted_data["output"]

                curr_training_data.append({
                    "generation_idx": curr_generation_log["generation_idx"],
                    "input": curr_input,
                    "output": curr_output,
                    "correctness": curr_pass,
                    "statement_modified": curr_verification_log.get("statement_modified", True)
                })
            processed_data.append({
                "name": curr_data_record["Name"],
                "training_data": curr_training_data
            })
        utils.write_to_json(f"{processed_data_save_path}/processed_prover_training_data.json", processed_data)
        print(f"Processed data saved to {processed_data_save_path}/processed_prover_training_data.json, in total {len(processed_data)} records.")

        # Summarize the processed data
        total_theorem_number = len(processed_data)
        total_data_number = sum(len(record["training_data"]) for record in processed_data)
        total_passed_data_number = sum(
            sum(1 for data in record["training_data"] if data["correctness"]) 
            for record in processed_data
        )
        print("=" * 20 + " Summary " + "=" * 20)
        print(f"Total number of theorems: {total_theorem_number}")
        print(f"Total number of training data: {total_data_number}")
        print(f"Total number of passed training data: {total_passed_data_number}")
        print(f"Total pass rate: {total_passed_data_number / total_data_number if total_data_number > 0 else 0:.2f}")
        print("=" * 50)

        data_state_dict = {
            "total_theorem_number": total_theorem_number,
            "total_data_number": total_data_number,
            "total_passed_data_number": total_passed_data_number,
            "total_pass_rate": total_passed_data_number / total_data_number if total_data_number > 0 else 0
        }
        return data_state_dict

    def preprocess_NL_fuser_training_data(
            self, 
            processed_data_save_path: str,
            max_pass_rate: float = 0.2, 
            min_pass_rate: float = 0.0,
            LLM_type: str = "Qwen3"
    ):
        """
        This function preprocesses the data for the NL fuser training, it will filter the data based on the pass rate. 
        It will process the class saved data into a list of dict following the following format:
            - "name": The name of the theorem, which is used to identify the theorem.
            - "input": The input text for the model, which is the prompt, in the Qwen3 case, it will also include the <think>\n\n<\\think> part because we use reset thinking in such generation.
            - "output": The output text for the model, which is the generated content.
            - "correctness": A 0~1 float variable indicating (1 - pass_rate) * (1 - statement_modification_rate) 
                and it will be 0 if the pass_rate is 0 (the statement maybe unsolvable). This is used as reward of the NL fuser model. 
        :param processed_data_save_path: The path to save the processed data. It will save the entir processed data as a json file named `processed_NL_fuser_training_data.json` representing list of dict.
        :param max_pass_rate: The max pass rate for the data to be included in the training data, default is 0.2.
        :param min_pass_rate: The min pass rate for the data to be included in the training data, default is 0.0.
        :param LLM_type: The type of the LLM, default is "Qwen3". It will be used to extract the input and the output text from the generated content.
        """

        utils.check_folder_exit(processed_data_save_path)

        processed_data = []

        for curr_data_record in self.verified_proofs:
            
            if "pass_rate" in curr_data_record:
                curr_pass_rate = curr_data_record["pass_rate"]

                # if min_pass_rate < curr_pass_rate <= max_pass_rate:
                #     if curr_pass_rate > 0.0:
                #         correctness = 1.0
                #     else:
                #         correctness = 0.0
                # else:
                #     correctness = 0.0

                if curr_pass_rate > 0.0:
                    correctness = (1 - curr_pass_rate) * (1 - curr_data_record.get("statement_modification_rate", 1.0))
                else:
                    correctness = 0.0
            else:
                print(f"Skipping record {curr_data_record['Name']} due to missing pass rate.")
                continue

            # correctness = True
            # if "pass_rate" not in curr_data_record:
            #     print(f"Skipping record {curr_data_record['Name']} due to missing pass rate.")
            #     continue
            # elif not (min_pass_rate < curr_data_record["pass_rate"] <= max_pass_rate):
            #     correctness = False
            if "Generation_log" not in curr_data_record or "Statement_fusion_log" not in curr_data_record["Generation_log"]:
                print(f"Skipping record {curr_data_record['Name']} due to missing generation log.")
                continue
            if "Response" not in curr_data_record["Generation_log"]["Statement_fusion_log"]:
                print(f"Skipping record {curr_data_record['Name']} due to missing response in statement fusion log.")
                continue

            curr_input = ""
            curr_output = ""

            if self.recorded_input:
                if "Input" in curr_data_record["Generation_log"]["Statement_fusion_log"] and "Response" in curr_data_record["Generation_log"]["Statement_fusion_log"]:
                    curr_input = curr_data_record["Generation_log"]["Statement_fusion_log"]["Input"]
                    curr_output = curr_data_record["Generation_log"]["Statement_fusion_log"]["Response"][len(curr_input):]
                else:
                    continue
            elif LLM_type == "Qwen3" and not self.recorded_input:
                extracted_data = self._Qwen3_extract_prompt_and_response(
                    curr_data_record["Generation_log"]["Statement_fusion_log"]["Response"], 
                    skip_thinking=True
                )
                if extracted_data is None:
                    print(f"Skipping record {curr_data_record['Name']} due to failed extraction of prompt and response.")
                    continue
                curr_input = extracted_data["input"]
                curr_output = extracted_data["output"]

            else:
                raise NotImplementedError(f"LLM type {LLM_type} is not supported yet, please implement the extraction function for it.")
            
            processed_data.append({
                "name": curr_data_record["Name"], 
                "input": curr_input,
                "output": curr_output, 
                "correctness": correctness
            })
        utils.write_to_json(f"{processed_data_save_path}/processed_NL_fuser_training_data.json", processed_data)

        print(f"Processed data saved to {processed_data_save_path}/processed_NL_fuser_training_data.json, in total {len(processed_data)} records.")

        # Summarize the processed data
        total_theorem_number = len(processed_data)
        total_passed_data_number = sum(1 for record in processed_data if record["correctness"])
        print("=" * 20 + " Summary " + "=" * 20)
        print(f"Total number of theorems: {total_theorem_number}")
        print(f"Total number of passed training data: {total_passed_data_number}")
        print(f"Total pass rate: {total_passed_data_number / total_theorem_number if total_theorem_number > 0 else 0:.2f}")
        print("=" * 50)

        data_state_dict = {
            "total_theorem_number": total_theorem_number,
            "total_passed_data_number": total_passed_data_number,
            "total_pass_rate": total_passed_data_number / total_theorem_number if total_theorem_number > 0 else 0
        }
        return data_state_dict

